#!/bin/bash
# ================================================
# Автомиграции конфига Hysteria 2
#   1) auth: password   -> auth: userpass   (старое)
#   2) auth: userpass   -> auth: command    (внешний скрипт, без рестартов)
# ================================================

migrate_auth() {
    # Если уже на внешней аутентификации — старая миграция не нужна.
    grep -qE '^[[:space:]]*type:[[:space:]]*command' "$CONFIG" 2>/dev/null && return 0

    if grep -q 'type: password' "$CONFIG" 2>/dev/null; then
        echo "⚠️  Обнаружен старый тип auth: password"
        echo "   Переключаю на userpass..."
        sed -i 's/type: password/type: userpass/' "$CONFIG"
        sed -i '/^  password:/d' "$CONFIG"
        if ! grep -q '^  userpass:' "$CONFIG"; then
            sed -i '/^auth:/a \  userpass:' "$CONFIG"
        fi
        echo "✅ Переключено на userpass."
    fi
    if ! grep -q '^  userpass:' "$CONFIG" 2>/dev/null; then
        if grep -q '^auth:' "$CONFIG"; then
            sed -i '/^auth:/a \  userpass:' "$CONFIG"
        fi
    fi
}

# Записывает скрипт внешней аутентификации. Hysteria вызывает его на КАЖДОЕ
# подключение с аргументами: $1=addr, $2=auth("user:pass"), $3=tx.
# При успехе печатает id пользователя (имя) и выходит с кодом 0.
# Благодаря этому добавление/удаление пользователя в users.db применяется
# сразу же — рестарт сервера не требуется.
#
# ВАЖНО: скрипт НЕ режет по числу сессий (это и сейчас так).
# Раньше здесь была жёсткая проверка лимита устройств прямо на этапе auth — она
# отклоняла новое подключение по «живому онлайну». На практике это ломало работу:
#   • собственная переподключающаяся/«залипшая» сессия клиента считалась лишней,
#     новый коннект отклонялся → клиент подключался и тут же отваливался (оффлайн);
#   • смена ноды не работала — старая нода ещё числила юзера онлайн, и новая
#     отказывала.
# Поэтому лимит устройств держится НЕ на входе, а по РЕАЛЬНОМУ трафику: раз в
# минуту менеджер смотрит, на каких нодах юзер активно гонит трафик (скорость за
# минуту ≥ порога), и оставляет активной только «первую» ноду, а лишние
# параллельные обрезает (см. enforce_active_node_limit). Так пинги/keepalive
# лимит не расходуют, а одну подписку нельзя активно использовать сразу на
# нескольких нодах.
#
# Единственный отказ, который скрипт всё же может выдать, — ЗАНЯТЫЙ СЛОТ
# (SLOT_REJECT=1, по умолчанию выключено). Он не про число сессий: слот привязан
# к конкретному креду и к адресу, который его занял, поэтому собственное
# переподключение и переезд на другую ноду под него не попадают, а вот вторая
# голова на той же ссылке — попадает. Разбор — docs/guide/SLOTS.md.
install_auth_script() {
    {
        echo '#!/bin/bash'
        echo "DB=\"${USERS_DB}\""
        echo "MAP=\"${AUTHMAP_FILE}\""
        echo "SLOTS=\"${SLOTPASS_DB}\""
        echo "SLOTMAP=\"${SLOTMAP_FILE}\""
        echo "NODECONF=\"${NODE_CONF}\""
        echo "APISECRET=\"${API_SECRET_FILE}\""
        echo "APIPORT=\"${API_PORT}\""
        cat <<'AUTHEOF'
# Внешняя аутентификация Hysteria 2 (auth.type: command).
# Вызывается на КАЖДОЕ подключение: $1=addr, $2="user:pass", $3=tx.
# При успехе печатает id (имя юзера) и выходит с кодом 0.
auth="$2"
[ -z "$auth" ] && exit 1
user="${auth%%:*}"
pass="${auth#*:}"
{ [ -z "$user" ] || [ "$user" = "$auth" ]; } && exit 1   # нет двоеточия — отказ
[ -r "$DB" ] || exit 1

# Проверка пары user:pass по базе. Число устройств ЮЗЕРА здесь не считается:
# резать по нему на auth ломало переподключения и переезд между нодами.
# Отказать может только занятый СЛОТ (ниже) — счёт идёт по сессиям одной
# конкретной ссылки, а не по всей подписке.
addr="$1"; ip="${addr%:*}"; ip="${ip#[}"; ip="${ip%]}"   # убрать :port и скобки IPv6

slot="-"    # каким кредом пришли: «-» = базовый пароль юзера, иначе токен ссылки
id="$user"  # что увидит движок: имя юзера или id слота (см. ниже)
awk -F: -v u="$user" -v p="$pass" '
    $1==u { rest=substr($0, length($1)+2); if (rest==p) { found=1; exit } }
    END { exit (found?0:1) }
' "$DB" || {
    # Пароль слота: у каждой доп. ссылки подписки свой (docs/design/SLOTS).
    # Второй awk идёт только когда базовый пароль не подошёл, то есть на
    # обычном подключении лишней работы нет. id наружу — по-прежнему имя
    # юзера: на нём держится весь учёт (трафик, онлайн, кик, tc-классы).
    [ -r "$SLOTS" ] || exit 1
    line=$(awk -F'|' -v u="$user" -v p="$pass" '$1==u && $2==p { print; exit }' "$SLOTS")
    [ -n "$line" ] || exit 1
    slot=$(printf '%s' "$line" | cut -d'|' -f3)
    id=$(printf '%s' "$line" | cut -d'|' -f4)
    [ -n "$id" ] || id="$user"
}

# Занятый слот не пускает второе устройство. Включается на ноде:
# SLOT_REJECT=1 в node.conf (по умолчанию выключено — это единственное место,
# где менеджер ОТКАЗЫВАЕТ в подключении, включать надо осознанно).
#
# Считаем ЖИВЫЕ СЕССИИ ЭТОГО СЛОТА, а не адреса: движок ведёт их отдельно по
# id, который мы только что выбрали, и два устройства за одним домашним NAT
# дают две сессии — по адресам они неразличимы (guide/SLOTS.md §6).
# Спрашиваем API на каждом подключении: минутный снимок тут не годится, иначе
# собственное переподключение упиралось бы в собственную же старую запись.
# API молчит — пускаем (fail-open): аутентификация не должна падать из-за него.
#
# Слот занят -> просто отказ, занявшего не трогаем. Кик отсюда пробовали: он не
# срабатывает вовсе (движок занят нашим же вызовом auth), и это оказалось к
# лучшему — измерено на изолированном инстансе:
#   • занявший слот продолжает работать, а отказ получает только пришедший;
#   • «проверка пинга» в клиенте, которая дёргает подключение при живом
#     туннеле, не рвёт этот туннель — просто не проходит.
# Цена: после ОБРЫВА без закрытия сессии слот держится ещё ~20-30 с (таймаут
# QUIC), и всё это время своё же устройство переподключиться не может. Замерено:
# сессия числилась живой ~25 с, дальше вход открывался сам.
if grep -q '^SLOT_REJECT=1' "$NODECONF" 2>/dev/null && [ -r "$APISECRET" ]; then
    maxs=$(sed -n 's/^SLOT_MAX_SESSIONS=\([0-9]\+\).*/\1/p' "$NODECONF" 2>/dev/null | head -1)
    [ -n "$maxs" ] || maxs=1
    secret=$(cat "$APISECRET" 2>/dev/null)
    # Разбираем {"user":2,"user.ab12cd34":1} без jq: он стоит ~100 мс на запуск,
    # а это вызов на КАЖДОЕ подключение. Ключ сравниваем целиком — в id есть и
    # точка, и цифры, так что «вырезать все цифры» из строки нельзя.
    live=$(curl -s --max-time 2 -H "Authorization: $secret" \
             "http://127.0.0.1:${APIPORT}/online" 2>/dev/null \
           | tr '{,}' '\n' \
           | awk -F':' -v k="$id" '{ gsub(/[" ]/,"",$1); gsub(/[^0-9]/,"",$2)
                                     if ($1==k && $2!="") { print $2; exit } }')
    [ -n "$live" ] && [ "$live" -ge "$maxs" ] 2>/dev/null && exit 1
fi
[ -n "$ip" ] && printf '%s|%s|%s|%s\n' "$user" "$slot" "$ip" "$(date +%s)" >> "$SLOTMAP" 2>/dev/null

# Живой маппинг user→IP для тарифного шейпинга скорости (klimit_reconcile в perf.sh).
# Один короткий append на подключение (строка < PIPE_BUF → атомарна), файл создаётся
# под пользователем сервиса в DATA_DIR. Ошибки записи глушим — на auth не влияют.
if [ -n "$MAP" ] && [ -n "$ip" ]; then
    printf '%s|%s|%s\n' "$user" "$ip" "$(date +%s)" >> "$MAP" 2>/dev/null
fi

printf '%s\n' "$id"
exit 0
AUTHEOF
    } > "$AUTH_SCRIPT"
    # Владение/права выставляет secure_auth_files — отдаёт их пользователю
    # сервиса, чтобы процесс hysteria гарантированно мог выполнить скрипт.
    secure_auth_files
}

# Заменяет секцию auth конфига на внешнюю аутентификацию командой.
rewrite_auth_section() {
    local tmp
    tmp=$(mktemp) || return 1
    awk -v cmd="$AUTH_SCRIPT" '
        /^auth:/ {
            print "auth:"
            print "  type: command"
            print "  command: " cmd
            skip=1
            next
        }
        skip && /^[[:space:]]/ { next }   # строки внутри блока auth — выкидываем
        skip && /^[^[:space:]]/ { skip=0 } # начался новый top-level ключ
        { print }
    ' "$CONFIG" > "$tmp" && cat "$tmp" > "$CONFIG"
    rm -f "$tmp"
}

# Разовый перевод на внешнюю аутентификацию. Идемпотентно: если уже command —
# просто обновляет скрипт и права. Делает ОДИН рестарт, дальше управление
# пользователями идёт без перезапусков. При сбое откатывает конфиг.
migrate_to_command_auth() {
    if grep -qE '^[[:space:]]*type:[[:space:]]*command' "$CONFIG" 2>/dev/null; then
        install_auth_script
        secure_auth_files
        return 0
    fi
    grep -q '^[[:space:]]*userpass:' "$CONFIG" 2>/dev/null || return 0

    echo "🔄 Перевожу аутентификацию на внешний скрипт"
    echo "   (разовый перезапуск — дальше пользователи добавляются/удаляются без рестартов)..."

    local bak="${CONFIG}.authbak.$(date +%s)"
    cp -a "$CONFIG" "$bak" 2>/dev/null

    # users.db из текущих userpass (не затирая уже существующие записи)
    touch "$USERS_DB"
    config_userpass_pairs | while IFS='|' read -r u p; do
        [ -n "$u" ] && [ -n "$p" ] || continue
        grep -q "^${u}:" "$USERS_DB" || printf '%s:%s\n' "$u" "$p" >> "$USERS_DB"
    done

    install_auth_script
    secure_auth_files

    # Защита от блокировки ВСЕХ: если в базу не попало ни одной пары (старый
    # формат не распарсился), переключаться на command нельзя — иначе остались
    # бы вообще без рабочей аутентификации. Конфиг не трогаем.
    if ! grep -q '[^[:space:]]' "$USERS_DB" 2>/dev/null; then
        echo "❌ База пользователей пуста — миграция отменена, конфиг не изменён."
        return 1
    fi

    # Самопроверка на первой паре из базы, ИЗ-ПОД ПОЛЬЗОВАТЕЛЯ СЕРВИСА — именно
    # так скрипт будет вызывать Hysteria. Ловит и логику, и проблемы с правами.
    # Если не прошла, конфиг НЕ трогаем и сервер НЕ перезапускаем.
    local tu tp
    IFS=: read -r tu tp < "$USERS_DB"
    if ! auth_check_as_service "$tu" "$tp"; then
        echo "❌ Скрипт аутентификации не прошёл самопроверку — миграция отменена, ничего не изменено."
        return 1
    fi

    rewrite_auth_section
    secure_auth_files

    systemctl restart "$SERVICE" 2>/dev/null
    sleep 2
    if systemctl is-active --quiet "$SERVICE" 2>/dev/null; then
        clear_restart_pending
        echo "✅ Готово. Пользователи теперь применяются мгновенно, без перезапуска Hysteria."
        sleep 2
    else
        echo "❌ Hysteria не запустилась — откатываю конфиг."
        cp -a "$bak" "$CONFIG" 2>/dev/null
        systemctl restart "$SERVICE" 2>/dev/null
        sleep 2
    fi
}
